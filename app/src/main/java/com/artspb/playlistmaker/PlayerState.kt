package com.artspb.playlistmaker

/**
 * Перечисление (enum) возможных состояний аудиоплеера.
 * Написано по рекомендации ревьюера вместо разрозненных Int-констант.
 *
 * Почему это Best Practices:
 * 1. Типобезопасность (Type Safety): исключает возможность случайно записать некорректное число.
 * 2. Исчерпываемость ветвлений (Exhaustive When): компилятор Kotlin автоматически проверяет,
 *    что в блоках when обработаны все возможные состояния плеера.
 */
enum class PlayerState {
    DEFAULT,
    PREPARED,
    PLAYING,
    PAUSED
}
